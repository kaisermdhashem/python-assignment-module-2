# 1. Taking student name as input
name = input("Enter student name: ")

# 2. Taking marks for 3 subjects as input
subject1 = float(input("Enter marks for Subject 1: "))
subject2 = float(input("Enter marks for Subject 2: "))
subject3 = float(input("Enter marks for Subject 3: "))

# 3. Calculating total and average
total = subject1 + subject2 + subject3
average = total / 3

# 4. Determining grades as per given specification
if average >= 80:
    grade = "A+"
elif average >= 70:
    grade = "A"
elif average >= 60:
    grade = "B"
elif average >= 50:
    grade = "C"
else:
    grade = "F"

# 5. Displaying result using f-string
print("\n----- STUDENT RESULT -----")
print(f"Student Name: {name}")
print(f"Total Marks: {total:.0f}")
print(f"Average: {average:.2f}")
print(f"Grade: {grade}")